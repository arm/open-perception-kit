"""Regenerate complete, model-independent Torch log-mel golden tensors.

Run: python3 development/tests/generate_log_mel_reference.py
Then: clang-format -i development/tests/log_mel_reference.h
Only regeneration needs numpy/torch/torchaudio; native tests include the header.
"""
from collections import deque
from pathlib import Path

import numpy as np
import torch
import torchaudio

# name, PCM window, FFT, Hann, hop, mel bins, frequency limits, log offset,
# normalization, epsilon, history frames, scheduled windows
CASES = (
    ('raw', 1024, 256, 201, 80, 23, 80, 7600, 1e-5, 'none', None, None, 1),
    ('window', 2000, 400, 320, 160, 32, 125, 6800, 1e-4, 'window', 1e-5, None, 1),
    ('rolling', 384, 384, 300, 128, 24, 50, 7800, 1e-7, 'rolling', 1e-6, 7, 21),
    ('minimum', 4, 4, 2, 1, 1, 0, 8000, 1e-6, 'none', None, None, 1),
)


def waveform(count):
    index = np.arange(count, dtype=np.int64)
    return (((index * 37) % 101 - 50) / 250.0 + ((index * 13) % 31 - 15) / 150.0).astype(np.float32)


def f32(value):
    text = format(float(np.float32(value)), '.9g')
    return text + ('f' if '.' in text or 'e' in text else '.0f')


def main():
    torch.set_num_threads(1)
    license_text = '\n'.join(Path(__file__).read_text().splitlines()[1:15])
    lines = [license_text.replace('# ', '// ').replace('\n#', '\n//'), '', '#pragma once', '',
             '// Generated by: python3 development/tests/generate_log_mel_reference.py',
             '// Then: clang-format -i development/tests/log_mel_reference.h',
             f'// Torch {torch.__version__}; torchaudio {torchaudio.__version__}; Float32 HTK/power2,',
             '// periodic Hann, center=False, no padding; Float64 normalization reductions.',
             '#include "preproc/CpuLogMelSpectrogram.h"', '#include <array>', '#include <span>', '',
             'namespace log_mel_reference {',
             'using Config = opk::stdop::preproc::LogMelSpectrogramConfig;', '',
             'struct Case {', '    const char *name;', '    Config config;', '    size_t bins;',
             '    size_t windows;', '    std::span<const float> expected;', '};', '']
    entries = []
    for name, window, fft, hann, hop, bins, low, high, offset, mode, epsilon, history, windows in CASES:
        transform = torchaudio.transforms.MelSpectrogram(
            sample_rate=16000, n_fft=fft, win_length=hann, hop_length=hop,
            f_min=low, f_max=high, n_mels=bins, window_fn=torch.hann_window,
            power=2.0, normalized=False, center=False, pad=0, norm=None,
            mel_scale='htk', wkwargs={'periodic': True})
        pcm = waveform(window + (windows - 1) * hop)
        moments = deque(maxlen=history) if history is not None else None
        output = []
        for step in range(windows):
            segment = torch.from_numpy(pcm[step * hop:step * hop + window])
            raw = (transform(segment) + np.float32(offset)).log().T.contiguous()
            if mode == 'none':
                normalized = raw
            else:
                wide = raw.double()
                if mode == 'window':
                    mean, deviation = wide.mean(), wide.std(correction=1)
                else:
                    moments.append((wide.mean(), wide.square().mean()))
                    mean = torch.stack([pair[0] for pair in moments]).mean()
                    second = torch.stack([pair[1] for pair in moments]).mean()
                    deviation = (second - mean.square()).clamp_min(0).sqrt()
                normalized = ((wide - mean) / (deviation + epsilon)).float()
            output.extend(normalized.flatten().tolist())
        assert np.isfinite(output).all()
        lines += [f'inline constexpr std::array<float, {len(output)}> {name}{{{{']
        for start in range(0, len(output), 6):
            lines.append('    ' + ', '.join(f32(value) for value in output[start:start + 6]) + ',')
        lines += ['}};', '']
        normalization = {'none': 'std::monostate{}',
                         'window': f'Config::WindowNormalization{{{epsilon}}}',
                         'rolling': f'Config::RollingNormalization{{{epsilon}, {history}}}'}[mode]
        config = (f'{{{window}, {fft}, {hann}, {hop}, {low}, {high}, {f32(offset)}, '
                  f'Config::Layout::TimeMajor, {normalization}}}')
        entries.append(f'    {{"{name}", {config}, {bins}, {windows}, {name}}},')
    lines += ['inline const std::array<Case, 4> cases{{', *entries, '}};',
              '} // namespace log_mel_reference', '']
    path = Path(__file__).with_name('log_mel_reference.h')
    path.write_text('\n'.join(lines))
    print(path)


if __name__ == '__main__':
    main()
