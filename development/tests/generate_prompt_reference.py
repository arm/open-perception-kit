"""Generate a synthetic mask-decoding fixture; no model or upstream code is executed.

The transform order follows Arm/mobile-sam-int8-xnnpack-executorch at
cced0b5344c7f01c731df32955290adf1fe7eae1/example.py. PyTorch is a fixture
creation dependency only. Normal native tests consume the checked-in header.
Run: python3 development/tests/generate_prompt_reference.py
Then: clang-format -i development/tests/prompt_reference.h
"""

from pathlib import Path

import torch
import torch.nn.functional as functional


def declaration(name: str, values: list) -> str:
    literals = [str(int(value)) for value in values]
    rows = [", ".join(literals[index:index + 8]) for index in range(0, len(literals), 8)]
    return f"inline constexpr std::array<uint8_t, {len(values)}> {name}{{\n    " + ",\n    ".join(rows) + "\n};\n"


def main() -> None:
    y, x = torch.meshgrid(torch.arange(256), torch.arange(256), indexing="ij")
    logits = ((x * 13 + y * 7) % 23 - 11).float().reshape(1, 1, 256, 256)
    binary = functional.interpolate(logits, size=(1024, 1024), mode="bilinear", align_corners=False) > 0
    native = functional.interpolate(binary.float(), size=(7, 13), mode="nearest").to(torch.uint8)
    notice_lines = Path(__file__).read_text().split('\n"""', 1)[0].splitlines()[1:]
    notice = "\n".join(notice_lines).replace("# ", "// ").replace("\n#", "\n//") + "\n"
    output = notice + f"// Generated by generate_prompt_reference.py with PyTorch {torch.__version__}.\n"
    output += "// Synthetic transform reference only; this does not establish model parity.\n#pragma once\n\n#include <array>\n#include <cstdint>\n\nnamespace prompt_reference {\n\n"
    output += declaration("NativeMask", native.flatten().tolist())
    output += "\n} // namespace prompt_reference\n"
    Path(__file__).with_name("prompt_reference.h").write_text(output)


if __name__ == "__main__":
    main()
