// The sole owner of WebUI design assets. Normal builds use the offline snapshot.
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {cp, mkdir, mkdtemp, readFile, rm, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const vendor = fileURLToPath(new URL('./content/vendor/', import.meta.url));
const waferCommit = '41ef08db5fb12c1aef580206bd452f9250d6152c';
const lucideVersion = '1.61.0';
const lucideIntegrity = 'sha512-yLAiQB3MWUJEstsEDAwenSA3m7vr1tdLvgnC16Q/XMxRRma0DWwMs8M2bWlvgShrIs1m2mWMJ+0AiahqQO4GrA==';
const icons = ['check', 'chevron-down', 'chevron-right', 'copy', 'eye', 'eye-off',
    'info', 'layers', 'panel-bottom', 'panel-left', 'pause', 'play', 'trash-2', 'volume-2', 'volume-x'];
const temporary = await mkdtemp(path.join(tmpdir(), 'opk-web-vendor-'));
const run = (command, args, cwd = temporary) => execFileSync(command, args, {cwd, stdio: 'inherit'});

try {
    run('gh', ['repo', 'clone', 'Arm-Debug/design-system', 'wafer', '--', '--depth', '1', '--branch', 'v2.0.2']);
    const source = path.join(temporary, 'wafer');
    const revision = execFileSync('git', ['rev-parse', 'HEAD'], {cwd: source, encoding: 'utf8'}).trim();
    if (revision !== waferCommit) throw new Error('Unexpected Wafer revision');
    run('npm', ['ci', '--ignore-scripts'], source);
    run('npm', ['run', 'build'], source);
    const css = await readFile(path.join(source, 'dist/wafer.css'), 'utf8');
    // Upstream 2.0.2 uses invalid fallback lists in @font-face descriptors.
    // Correct only those descriptors; token values and typography stay upstream-owned.
    const compatibleCss = css.replaceAll('font-family:Lato,sans-serif;', 'font-family:Lato;')
        .replaceAll('font-family:Cousine,monospace;', 'font-family:Cousine;');

    run('npm', ['pack', `lucide-static@${lucideVersion}`, '--ignore-scripts', '--silent']);
    const archive = path.join(temporary, `lucide-static-${lucideVersion}.tgz`);
    const integrity = 'sha512-' + createHash('sha512').update(await readFile(archive)).digest('base64');
    if (integrity !== lucideIntegrity) throw new Error('Unexpected Lucide package integrity');
    run('tar', ['-xzf', archive, 'package/LICENSE', ...icons.map((name) => `package/icons/${name}.svg`)]);

    for (const name of ['wafer', 'lucide']) await rm(path.join(vendor, name), {recursive: true, force: true});
    await mkdir(path.join(vendor, 'wafer'), {recursive: true});
    await writeFile(path.join(vendor, 'wafer/wafer.css'), `/* Copyright (C) 2025 Arm Limited. See NOTICE. */\n${compatibleCss}`);
    await cp(path.join(source, 'dist/fonts'), path.join(vendor, 'wafer/fonts'), {recursive: true});
    await cp(path.join(source, 'dist/LICENSES'), path.join(vendor, 'wafer/LICENSES'), {recursive: true});
    await writeFile(path.join(vendor, 'wafer/NOTICE'), `Wafer 2.0.2 — Copyright (C) 2025 Arm Limited.\nSource: https://github.com/Arm-Debug/design-system/tree/${waferCommit}\nBuilt by development/web/update-vendor.mjs.\nOnly font-face family descriptors are normalized for browser compatibility.\nLato and Cousine license texts are preserved in LICENSES/.\n`);
    await mkdir(path.join(vendor, 'lucide'), {recursive: true});
    for (const name of icons) await cp(path.join(temporary, `package/icons/${name}.svg`), path.join(vendor, `lucide/${name}.svg`));
    await cp(path.join(temporary, 'package/LICENSE'), path.join(vendor, 'lucide/LICENSE'));
    await writeFile(path.join(vendor, 'lucide/icons.css'), `/* Lucide ${lucideVersion}; see LICENSE. Generated by update-vendor.mjs. */\n`
        + icons.map((name) => `[data-icon="${name}"] { mask-image: url("${name}.svg"); }`).join('\n') + '\n');
    console.log('Updated Wafer and Lucide assets.');
} finally {
    await rm(temporary, {recursive: true, force: true});
}
