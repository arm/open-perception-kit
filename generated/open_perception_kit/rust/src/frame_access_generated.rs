            pub struct FrameReplyBuilder<'a: 'b, 'b, A: flatbuffers::Allocator + 'a> {
                fbb_: &'b mut flatbuffers::FlatBufferBuilder<'a, A>,
                start_: flatbuffers::WIPOffset<flatbuffers::TableUnfinishedWIPOffset>,
            }
            impl<'a: 'b, 'b, A: flatbuffers::Allocator + 'a> FrameReplyBuilder<'a, 'b, A> {
                #[inline]
                pub fn add_status(&mut self, status: ReplyStatus) {
                    self.fbb_.push_slot::<ReplyStatus>(
                        FrameReply::VT_STATUS,
                        status,
                        ReplyStatus::Unspecified,
                    );
                }
                #[inline]
                pub fn add_sample(&mut self, sample: flatbuffers::WIPOffset<SampleInfo<'b>>) {
                    self.fbb_
                        .push_slot_always::<flatbuffers::WIPOffset<SampleInfo>>(
                            FrameReply::VT_SAMPLE,
                            sample,
                        );
                }
                #[inline]
                pub fn add_opk_results(
                    &mut self,
                    opk_results: flatbuffers::WIPOffset<flatbuffers::Vector<'b, u8>>,
                ) {
                    self.fbb_.push_slot_always::<flatbuffers::WIPOffset<_>>(
                        FrameReply::VT_OPK_RESULTS,
                        opk_results,
                    );
                }
                #[inline]
                pub fn add_frame(&mut self, frame: flatbuffers::WIPOffset<Frame<'b>>) {
                    self.fbb_.push_slot_always::<flatbuffers::WIPOffset<Frame>>(
                        FrameReply::VT_FRAME,
                        frame,
                    );
                }
                #[inline]
                pub fn add_error_message(
                    &mut self,
                    error_message: flatbuffers::WIPOffset<&'b str>,
                ) {
                    self.fbb_.push_slot_always::<flatbuffers::WIPOffset<_>>(
                        FrameReply::VT_ERROR_MESSAGE,
                        error_message,
                    );
                }
                #[inline]
                pub fn new(
                    _fbb: &'b mut flatbuffers::FlatBufferBuilder<'a, A>,
                ) -> FrameReplyBuilder<'a, 'b, A> {
                    let start = _fbb.start_table();
                    FrameReplyBuilder {
                        fbb_: _fbb,
                        start_: start,
                    }
                }
                #[inline]
                pub fn finish(self) -> flatbuffers::WIPOffset<FrameReply<'a>> {
                    let o = self.fbb_.end_table(self.start_);
                    flatbuffers::WIPOffset::new(o.value())
                }
            }

