                pub const VT_SAMPLE: flatbuffers::VOffsetT = 6;
                pub const VT_OPK_RESULTS: flatbuffers::VOffsetT = 8;
                pub const VT_FRAME: flatbuffers::VOffsetT = 10;
                pub const VT_ERROR_MESSAGE: flatbuffers::VOffsetT = 12;

                #[inline]
                pub unsafe fn init_from_table(table: flatbuffers::Table<'a>) -> Self {
                    FrameReply { _tab: table }
                }
                #[allow(unused_mut)]
                pub fn create<
                    'bldr: 'args,
                    'args: 'mut_bldr,
                    'mut_bldr,
                    A: flatbuffers::Allocator + 'bldr,
                >(
                    _fbb: &'mut_bldr mut flatbuffers::FlatBufferBuilder<'bldr, A>,
                    args: &'args FrameReplyArgs<'args>,
                ) -> flatbuffers::WIPOffset<FrameReply<'bldr>> {
                    let mut builder = FrameReplyBuilder::new(_fbb);
                    if let Some(x) = args.error_message {
                        builder.add_error_message(x);
                    }
                    if let Some(x) = args.frame {
                        builder.add_frame(x);
                    }
                    if let Some(x) = args.opk_results {
                        builder.add_opk_results(x);
                    }
                    if let Some(x) = args.sample {
                        builder.add_sample(x);
                    }
                    builder.add_status(args.status);
                    builder.finish()
                }

